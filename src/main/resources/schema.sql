CREATE TABLE IF NOT EXISTS data_source (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  type VARCHAR(30) NOT NULL,
  connection_config VARCHAR(2000) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sync_task (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  source_id BIGINT NOT NULL,
  target_table VARCHAR(120) NOT NULL,
  sync_mode VARCHAR(20) NOT NULL,
  schedule_expression VARCHAR(80),
  status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
  retry_count INT NOT NULL DEFAULT 0,
  last_error VARCHAR(2000),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_task_source FOREIGN KEY (source_id) REFERENCES data_source(id)
);

CREATE TABLE IF NOT EXISTS quality_rule (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  table_name VARCHAR(120) NOT NULL,
  rule_type VARCHAR(40) NOT NULL,
  expression VARCHAR(500) NOT NULL,
  severity VARCHAR(20) NOT NULL DEFAULT 'ERROR',
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);


CREATE TABLE IF NOT EXISTS task_run (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_key VARCHAR(100) NOT NULL UNIQUE,
  task_id BIGINT NOT NULL,
  status VARCHAR(20) NOT NULL,
  records_read BIGINT NOT NULL DEFAULT 0,
  records_written BIGINT NOT NULL DEFAULT 0,
  error_message VARCHAR(2000),
  started_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  finished_at TIMESTAMP,
  CONSTRAINT fk_run_task FOREIGN KEY (task_id) REFERENCES sync_task(id)
);

CREATE TABLE IF NOT EXISTS quality_check_result (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rule_id BIGINT NOT NULL,
  task_run_id BIGINT,
  status VARCHAR(20) NOT NULL,
  checked_rows BIGINT NOT NULL DEFAULT 0,
  failed_rows BIGINT NOT NULL DEFAULT 0,
  message VARCHAR(1000),
  checked_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_result_rule FOREIGN KEY (rule_id) REFERENCES quality_rule(id),
  CONSTRAINT fk_result_run FOREIGN KEY (task_run_id) REFERENCES task_run(id)
);

CREATE TABLE IF NOT EXISTS audit_event (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_type VARCHAR(60) NOT NULL,
  resource_type VARCHAR(60) NOT NULL,
  resource_id VARCHAR(100),
  payload VARCHAR(4000),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS metric_definition (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  metric_key VARCHAR(100) NOT NULL UNIQUE,
  display_name VARCHAR(160) NOT NULL,
  unit VARCHAR(30),
  description VARCHAR(500),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

MERGE INTO metric_definition (metric_key, display_name, unit, description, active)
KEY(metric_key) VALUES ('pipeline_success_rate', 'Pipeline Success Rate', 'percent', 'Successful task runs divided by total task runs', TRUE);
MERGE INTO metric_definition (metric_key, display_name, unit, description, active)
KEY(metric_key) VALUES ('records_processed', 'Records Processed', 'rows', 'Total rows written by successful task runs', TRUE);
